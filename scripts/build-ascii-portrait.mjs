/**
 * Bakes the /profile statement wall's character field.
 *
 *   node scripts/build-ascii-portrait.mjs
 *
 * Reads `public/profile/portrait.webp` and writes `lib/ascii-portrait.ts` — a
 * plain string of ASCII characters that renders as the photograph, full bleed.
 *
 * ── What this is, measured against the reference ─────────────────────────
 * benjamincreative.me fills its whole panel with the picture: 1029×1188 CSS
 * pixels of characters, roughly 114×108 cells, edge to edge, with nothing
 * around it. An earlier version of this script put the portrait in 59 of 170
 * columns and filled the rest with grain, which read as a small picture sitting
 * in a field rather than as a wall — the thing the reference does.
 *
 * So the photograph is cropped to the grid's own aspect and covers every cell.
 *
 * ── Two things that have to agree ────────────────────────────────────────
 * 1. **Cells are 0.6 as wide as they are tall.** A COLS×ROWS grid therefore
 *    *displays* at (COLS × 0.6) : ROWS. The crop has to match that, not
 *    COLS:ROWS, or the face comes out stretched. That is why the crop is taken
 *    by hand with `extract` before the resize rather than left to `fit: cover`.
 * 2. **The crop is biased to the top.** The source is a 4:5 portrait and the
 *    grid is wider than that, so height is what gets cut. Cutting it from the
 *    bottom keeps the head and loses the collar; centring it would take the top
 *    of the hair off.
 *
 * The string is used twice: the server renders it into a `<pre>` (which is what
 * a crawler, a reader with JavaScript off, and anyone on reduced motion gets),
 * and the canvas in AsciiField.tsx reads it back out of that `<pre>` to get its
 * luminance map — so the picture is shipped exactly once.
 *
 * Regenerate after changing the source image, the grid or the ramp. The output
 * is committed; the site never runs this.
 */

import sharp from "sharp";
import { writeFile } from "node:fs/promises";

const SRC = "public/profile/portrait.webp";
const OUT = "lib/ascii-portrait.ts";

/** 128 × 82 cells ≈ 10,500 characters. In the same range as the reference's
 *  grid, and small enough that the field ships in about 2.5 KB gzipped. */
const COLS = 128;
const ROWS = 82;
const CELL_ASPECT = 0.6;

/** Light → dark. No space: the reference's field covers its whole panel, and
 *  holes read as damage rather than as shading.
 *
 *  ⚠ This ramp is duplicated in components/profile/AsciiField.tsx, which maps
 *  each character back to a brightness level. Change one, change both. */
const RAMP = ".,:;+=*#$@";

const meta = await sharp(SRC).metadata();

/* The crop, in source pixels. The grid displays at this aspect; anything else
   and the face is stretched — see note 1 in the header. */
const gridAspect = (COLS * CELL_ASPECT) / ROWS;
let cropW = meta.width;
let cropH = Math.round(meta.width / gridAspect);

if (cropH > meta.height) {
  cropH = meta.height;
  cropW = Math.round(meta.height * gridAspect);
}

const { data: px } = await sharp(SRC)
  .extract({
    left: Math.round((meta.width - cropW) / 2),
    // Top-biased: the head is at the top of this frame.
    top: 0,
    width: cropW,
    height: cropH,
  })
  .resize(COLS, ROWS, { fit: "fill" })
  .grayscale()
  .raw()
  .toBuffer({ resolveWithObject: true });

/* ── Contrast ─────────────────────────────────────────────────────────────
   A phone photograph uses maybe half the available range. Mapped straight onto
   ten glyphs it comes out as three of them and the face disappears. The 1st and
   99th percentiles become black and white, and an S-curve on top pushes the
   midtones apart so the cheek, the beard and the background separate into
   different characters instead of sharing one. */
const lum = new Float32Array(COLS * ROWS);
for (let i = 0; i < lum.length; i++) lum[i] = px[i] / 255;

const sorted = Float32Array.from(lum).sort();
const lo = sorted[Math.floor(sorted.length * 0.01)];
const hi = sorted[Math.floor(sorted.length * 0.99)];

/** Smoothstep, which is the S-curve. */
const scurve = (t) => t * t * (3 - 2 * t);

const lines = [];
for (let y = 0; y < ROWS; y++) {
  let line = "";
  for (let x = 0; x < COLS; x++) {
    const raw = (lum[y * COLS + x] - lo) / (hi - lo || 1);
    const v = scurve(Math.min(1, Math.max(0, raw)));
    // Dark photograph → heavy glyph: on paper, ink is shadow.
    line += RAMP[Math.round((1 - v) * (RAMP.length - 1))];
  }
  lines.push(line);
}

const field = lines.join("\\n");

const file = `/* GENERATED by scripts/build-ascii-portrait.mjs — do not edit by hand.
   ${COLS}×${ROWS} characters of public/profile/portrait.webp, full bleed.
   Re-run the script after changing the source image, the grid or the ramp. */

export const ASCII_COLS = ${COLS};
export const ASCII_ROWS = ${ROWS};

export const ASCII_PORTRAIT =
  "${field}";
`;

await writeFile(OUT, file, "utf8");

const counts = {};
for (const ch of lines.join("")) counts[ch] = (counts[ch] ?? 0) + 1;
console.log(`wrote ${OUT}`);
console.log(`  grid      ${COLS}×${ROWS} = ${COLS * ROWS} cells`);
console.log(`  crop      ${cropW}×${cropH} from ${meta.width}×${meta.height} (aspect ${gridAspect.toFixed(3)})`);
console.log(`  contrast  stretched from ${lo.toFixed(3)}–${hi.toFixed(3)}`);
console.log(`  glyphs    ${[...RAMP].map((c) => `${c}:${counts[c] ?? 0}`).join("  ")}`);
